"""---
## Stage 6 — Repeat over all training images
167 training images, measures loss on the 42 development images, and saves the checkpoint with the lowest development loss.
"""

from datetime import datetime
from torch.utils.data import DataLoader

BATCH_SIZE = 4
EPOCHS = 10  # Starting value; adjust based on development results

train_loader = DataLoader(
    [str(path) for path in train_paths],
    batch_size=BATCH_SIZE,
    shuffle=True
)

dev_loader = DataLoader(
    [str(path) for path in dev_paths],
    batch_size=BATCH_SIZE,
    shuffle=False
)


def load_images(paths):
    """Open a batch of files as RGB PIL images."""
    images = []

    for path in paths:
        with Image.open(path) as image:
            images.append(image.convert("RGB"))

    return images


def feature_matching_loss(student_features, teacher_features):
    """MSE between L2-normalized patch feature vectors."""
    if student_features.shape != teacher_features.shape:
        raise ValueError(
            "Student and teacher feature shapes do not match."
        )

    student_unit = F.normalize(student_features, p=2, dim=1)
    teacher_unit = F.normalize(teacher_features, p=2, dim=1)

    return F.mse_loss(student_unit, teacher_unit)


def run_epoch(loader, training):
    """Train for one epoch or calculate development loss."""
    student_model.train(training)

    total_loss = 0.0
    total_images = 0

    for batch_paths in loader:
        images = load_images(batch_paths)

        # teacher.extract() uses the frozen teacher
        teacher_pixels, teacher_features = teacher.extract(images)

        if training:
            optimizer.zero_grad(set_to_none=True)

        # Gradients are enabled only for the training pass
        with torch.set_grad_enabled(training):
            student_features = student_model(teacher_pixels)

            loss = feature_matching_loss(
                student_features,
                teacher_features
            )

            if not torch.isfinite(loss).item():
                raise ValueError("Loss is not finite.")

            if training:
                loss.backward()
                optimizer.step()

        batch_size = len(images)
        total_loss += loss.item() * batch_size
        total_images += batch_size

    return total_loss / total_images


