"""---
## Stage 7 — Calculate an anomaly map and image score
"""

import math
import torch.nn.functional as F


@torch.no_grad()
def anomaly_score(image):
    """
    Return:
      1. A 224 x 224 teacher-student discrepancy map
      2. An image score: mean of the highest-scoring 1% of pixels
    """

    # Teacher preprocesses the image and extracts its features
    teacher_pixels, teacher_features = teacher.extract(
        image.convert("RGB")
    )

    # Student receives the same preprocessed image
    student_features = student_model(teacher_pixels)

    if teacher_features.shape != student_features.shape:
        raise ValueError("Teacher and student feature shapes do not match.")

    # Compare the 384-element feature vectors at each grid position.
    # Shape: [1, 14, 14]
    patch_map = 1 - F.cosine_similarity(
        teacher_features,
        student_features,
        dim=1
    )

    # Resize to the processed image size: [1, 1, 224, 224]
    image_map = F.interpolate(
        patch_map.unsqueeze(1),
        size=teacher_pixels.shape[-2:],
        mode="bilinear",
        align_corners=False
    )

    # Average the highest-scoring 1% of pixels
    flattened = image_map.flatten()
    k = max(1, math.ceil(0.01 * flattened.numel()))

    score = torch.topk(flattened, k).values.mean().item()

    return image_map[0, 0].cpu(), score

